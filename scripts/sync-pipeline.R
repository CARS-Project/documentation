# Copy the pipeline outputs this book uses into the book repository.
#
# Usage, from the book's root folder:
#   Rscript scripts/sync-pipeline.R
#
# The pipeline repository is ../MOT-pipline unless MOT_PIPELINE_DIR says
# otherwise. Which files are copied is set in data/manifest.yml. The pipeline's
# commit and build details are written to data/pipeline/provenance.csv so every
# page can say which build it describes.

pipeline_dir <- Sys.getenv("MOT_PIPELINE_DIR", "../MOT-pipline")
if (!dir.exists(pipeline_dir)) {
  stop("Pipeline repository not found at ", pipeline_dir,
       ". Set MOT_PIPELINE_DIR to its location.")
}

manifest <- yaml::read_yaml("data/manifest.yml")
out_dir <- "data/pipeline"

# Start from an empty folder so files dropped from the manifest disappear
unlink(out_dir, recursive = TRUE)
dir.create(out_dir, recursive = TRUE)

copy_one <- function(src_rel, dest) {
  dir.create(dirname(dest), recursive = TRUE, showWarnings = FALSE)
  ok <- file.copy(file.path(pipeline_dir, src_rel), dest, overwrite = TRUE)
  if (!ok) stop("Could not copy ", src_rel)
}

# Data files: globs expand against the pipeline repository
n_data <- 0
for (pattern in manifest$data) {
  matches <- Sys.glob(file.path(pipeline_dir, pattern))
  if (length(matches) == 0) stop("No pipeline file matches ", pattern)
  for (m in matches) {
    rel <- substring(m, nchar(pipeline_dir) + 2)
    copy_one(rel, file.path(out_dir, rel))
    n_data <- n_data + 1
  }
}

# Reports: the first heading is marked unnumbered, because the reports number
# their own sections, and given an id for cross-references
# (reports/mileage_report.md -> #sec-mileage-report). A note says where the
# chapter comes from.
for (r in manifest$reports) {
  src <- file.path(pipeline_dir, r$source)
  if (!file.exists(src)) stop("Report not found: ", r$source)
  lines <- readLines(src, encoding = "UTF-8", warn = FALSE)
  h1 <- grep("^# ", lines)[1]
  id <- sub("-report$", "", gsub("_", "-", sub("\\.md$", "", basename(r$dest))))
  lines[h1] <- paste0(lines[h1], " {#sec-", id, "-report .unnumbered}")
  note <- c(
    "",
    "::: {.callout-note title=\"Generated by the pipeline\"}",
    paste0("This appendix is `", r$source, "` from the MOT-pipline ",
           "repository, copied unchanged into the book by ",
           "`scripts/sync-pipeline.R`. Paths such as `outputs/...` refer to ",
           "that repository. See @sec-maintaining."),
    ":::",
    ""
  )
  lines <- append(lines, note, after = h1)
  dir.create(dirname(r$dest), recursive = TRUE, showWarnings = FALSE)
  writeLines(lines, r$dest, useBytes = TRUE)
  if (!is.null(r$figures)) {
    fig_dest <- file.path(dirname(r$dest), basename(r$figures))
    unlink(fig_dest, recursive = TRUE)
    dir.create(fig_dest, recursive = TRUE)
    figs <- list.files(file.path(pipeline_dir, r$figures), full.names = TRUE)
    file.copy(figs, fig_dest, overwrite = TRUE)
  }
}

# Provenance: which pipeline build this snapshot comes from
git <- function(...) {
  out <- tryCatch(
    system2("git", c("-C", shQuote(pipeline_dir), ...), stdout = TRUE,
            stderr = FALSE),
    error = function(e) NA_character_
  )
  if (length(out) == 0) NA_character_ else out[1]
}
parquet <- file.path(pipeline_dir, "outputs", "vehicles_enhanced_maximal.parquet")
provenance <- data.frame(
  item = c("pipeline_commit", "pipeline_commit_date", "pipeline_branch",
           "pipeline_uncommitted_changes", "parquet_modified", "synced_at"),
  value = c(
    git("rev-parse", "--short", "HEAD"),
    git("log", "-1", "--format=%cs"),
    git("rev-parse", "--abbrev-ref", "HEAD"),
    as.character(length(system2("git", c("-C", shQuote(pipeline_dir),
                                         "status", "--porcelain"),
                                stdout = TRUE)) > 0),
    if (file.exists(parquet)) format(file.mtime(parquet), "%Y-%m-%d") else NA,
    format(Sys.time(), "%Y-%m-%d %H:%M")
  )
)
write.csv(provenance, file.path(out_dir, "provenance.csv"), row.names = FALSE)

message("Copied ", n_data, " data files and ", length(manifest$reports),
        " reports from ", pipeline_dir, " (commit ",
        provenance$value[1], ").")
message("Next: Rscript scripts/run-examples.R (needs the parquet), then ",
        "Rscript scripts/rebuild.R")
